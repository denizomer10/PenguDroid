#!/usr/bin/env python3
"""Generate host GL forwarder modules for the native-bridge proxy build.

The Digitalis proxy blueprints `libberberis_proxy_libEGL`, `_libGLESv1_CM`,
`_libGLESv2` and `_libGLESv3` link against host modules named `libEGL`,
`libGLESv1_CM`, `libGLESv2` and `libGLESv3`. Those are AOSP host modules that are
not part of the pinned source slice, and a proxy resolves each guest call with
`dlsym(proxy_handle, name)`, so the proxy's dependency closure must export the
real entry points.

This module generates, for each of those four host modules, a self-contained
`cc_library_shared` whose exported functions are register-preserving
`jmp *slot(%rip)` stubs over one pointer table. A load-time constructor fills
the table by `dlopen`-ing the PenguDroid GL shim and the host Mesa/glvnd
libraries and looking each name up in those handles — never `RTLD_DEFAULT`,
because the forwarder's own stubs are in that scope and would self-bind.

Assembly stubs (rather than C wrappers) are required: GLES entry points take
floats and vectors, so a hand-written C wrapper would have to restate every
signature, and any mismatch silently corrupts argument registers.

Symbol names come from the NativeBridgeSupport stub sources, which are exactly
the names the guest can call and therefore the names the proxy must resolve.
"""

import re

# Host module name -> (guest stub library directory, sonames to load, in lookup
# order). The first soname entry is the PenguDroid shim: it owns the fake
# display, so its `egl*` implementations must win over Mesa's. Later entries
# supply everything the shim does not implement.
#
# Never list the unversioned name.  These modules are installed under exactly
# those names (`libEGL.so`, ...), so `dlopen("libEGL.so")` returns the module
# itself and `dlsym` on it returns the module's own stubs: every slot then
# points at the stub that jumps through it, and the guest spins on a `jmp` to
# itself with no syscall and no diagnostic.  Only versioned host sonames may
# appear here, and `own_module()` below enforces the same rule at run time.
HOST_MODULES = {
    "libEGL": (
        "libEGL",
        ("libpengudroid_gleshim.so", "libEGL.so.1", "libEGL.so.0"),
    ),
    "libGLESv1_CM": (
        "libGLESv1_CM",
        (
            "libpengudroid_gleshim.so",
            "libGLESv1_CM.so.1",
            "libGLESv1_CM_nvidia.so.1",
        ),
    ),
    "libGLESv2": (
        "libGLESv2",
        ("libpengudroid_gleshim.so", "libGLESv2.so.2", "libGLESv2.so.1"),
    ),
    "libGLESv3": (
        "libGLESv3",
        ("libpengudroid_gleshim.so", "libGLESv2.so.2", "libGLESv2.so.1"),
    ),
}

STUB_LIBRARIES = tuple(directory for directory, _ in HOST_MODULES.values())

_FUNCTION = re.compile(
    r"DEFINE_INTERCEPTABLE_STUB_FUNCTION\(\s*([A-Za-z_][A-Za-z0-9_]*)\s*\)"
)
_VARIABLE = re.compile(
    r"DEFINE_INTERCEPTABLE_STUB_VARIABLE\(\s*([A-Za-z_][A-Za-z0-9_]*)\s*\)"
)


class ForwarderError(RuntimeError):
    pass


def stub_symbols(source_text, origin="stub source"):
    """Return (functions, variables) exported by an NBS arm64 stub translation unit."""
    functions = _FUNCTION.findall(source_text)
    variables = _VARIABLE.findall(source_text)
    if not functions:
        raise ForwarderError("no interceptable functions found in " + str(origin))
    duplicates = {name for name in functions if functions.count(name) > 1}
    if duplicates:
        raise ForwarderError(
            "duplicate stub functions in %s: %s" % (origin, sorted(duplicates))
        )
    return functions, variables


def module_identifier(module):
    return module.replace(".", "_")


def assembly(module, functions):
    """Emit the `jmp *slot(%rip)` stubs plus the shared slot table for `module`."""
    tag = module_identifier(module)
    lines = [
        "// Generated by tools/gl-forwarders.py: do not edit.",
        "// Each entry point is a tail jump through one pointer table, so every",
        "// argument register, vector register and the return path stay intact.",
        "    .text",
    ]
    for index, name in enumerate(functions):
        lines += [
            "    .globl %s" % name,
            "    .type %s,@function" % name,
            "    .p2align 4",
            "%s:" % name,
            "    jmp *pd_%s_slots+%d(%%rip)" % (tag, index * 8),
            "    .size %s, .-%s" % (name, name),
        ]
    lines += [
        # Unresolved entries point here instead of at NULL: return 0 / +0.0f
        # with an empty vector register, which is the least damaging answer for
        # EGLBoolean, int, pointer and float returns alike.
        "    .globl pd_%s_unresolved" % tag,
        "    .hidden pd_%s_unresolved" % tag,
        "    .type pd_%s_unresolved,@function" % tag,
        "    .p2align 4",
        "pd_%s_unresolved:" % tag,
        "    xorps %xmm0, %xmm0",
        "    xorl %eax, %eax",
        "    ret",
        "    .size pd_%s_unresolved, .-pd_%s_unresolved" % (tag, tag),
        "    .section .bss",
        "    .globl pd_%s_slots" % tag,
        "    .hidden pd_%s_slots" % tag,
        "    .p2align 3",
        "pd_%s_slots:" % tag,
        "    .zero %d" % (len(functions) * 8),
        '    .section .note.GNU-stack,"",@progbits',
        "",
    ]
    return "\n".join(lines)


def initializer(module, functions, sonames):
    """Emit the constructor that resolves every slot for `module`."""
    tag = module_identifier(module)
    names = ", ".join('"%s"' % name for name in functions)
    soname_list = ", ".join('"%s"' % soname for soname in sonames)
    return """// Generated by tools/gl-forwarders.py: do not edit.
// Host-side dependency of libberberis_proxy_%(module)s. The NBS proxy resolves
// every guest call with dlsym(proxy_handle, name), which searches this
// library's closure, so the table below is what makes the proxy callable.
#define _GNU_SOURCE  // Dl_info/dladdr, used to reject this module's own stubs.
#include <dlfcn.h>
#include <stdio.h>
#include <stdlib.h>

extern void *pd_%(tag)s_slots[];
extern void pd_%(tag)s_unresolved(void);

static const char *const kNames[] = {%(names)s};
static const char *const kSonames[] = {%(sonames)s};

// Base address of this module, used to reject symbols that live in it.
static const void *g_own_base;

// True when `symbol` is one of this module's own stubs.  A slot that points at
// its own stub is an infinite indirect jump to itself: no syscall, no fault, no
// log, so the guest just burns a core.  Treat it as unresolved instead.
static int is_own_symbol(void *symbol) {
  Dl_info info;
  if (g_own_base == NULL || symbol == NULL) return 0;
  if (!dladdr(symbol, &info)) return 0;
  return info.dli_fbase == g_own_base;
}

static void *open_first_available(void) {
  const char *explicit_path = getenv("PENGUDROID_GLESHIM");
  if (explicit_path && *explicit_path) {
    void *handle = dlopen(explicit_path, RTLD_NOW | RTLD_LOCAL);
    if (handle) return handle;
  }
  int trace = getenv("PENGUDROID_GL_TRACE") != NULL;
  for (size_t i = 0; i < sizeof(kSonames) / sizeof(kSonames[0]); ++i) {
    void *handle = dlopen(kSonames[i], RTLD_NOW | RTLD_LOCAL);
    if (trace) fprintf(stderr, "[gl-forwarder] %(module)s: %%s %%s\\n", kSonames[i], handle ? "opened" : dlerror());
    if (handle) return handle;
  }
  return NULL;
}

// The shim implements the fake display; Mesa/glvnd provides everything else.
// Look the name up in each handle explicitly rather than with RTLD_DEFAULT,
// which would find this library's own stub and recurse forever.
static void *resolve(const char *name) {
  static void *handles[4];
  static size_t count;
  if (count == 0) {
    handles[count] = open_first_available();
    if (handles[count]) ++count;
    for (size_t i = 1; i < sizeof(kSonames) / sizeof(kSonames[0]); ++i) {
      void *handle = dlopen(kSonames[i], RTLD_NOW | RTLD_LOCAL);
      if (handle) handles[count++] = handle;
      if (count == sizeof(handles) / sizeof(handles[0])) break;
    }
  }
  for (size_t i = 0; i < count; ++i) {
    void *symbol = dlsym(handles[i], name);
    if (symbol && !is_own_symbol(symbol)) return symbol;
  }
  return NULL;
}

__attribute__((constructor)) static void pd_%(tag)s_init(void) {
  Dl_info own;
  size_t unresolved = 0;
  if (dladdr((void *)&pd_%(tag)s_slots[0], &own)) g_own_base = own.dli_fbase;
  for (size_t i = 0; i < sizeof(kNames) / sizeof(kNames[0]); ++i) {
    void *symbol = resolve(kNames[i]);
    if (symbol == NULL) {
      pd_%(tag)s_slots[i] = (void *)&pd_%(tag)s_unresolved;
      if (unresolved == 0) fprintf(stderr, "[gl-forwarder] %%s: unresolved", "%(module)s");
      fprintf(stderr, " %%s", kNames[i]);
      ++unresolved;
      continue;
    }
    pd_%(tag)s_slots[i] = symbol;
  }
  if (unresolved != 0) fprintf(stderr, " (%%zu of %%zu)\\n", unresolved,
                               sizeof(kNames) / sizeof(kNames[0]));
}
""" % {
        "module": module,
        "tag": tag,
        "names": names,
        "sonames": soname_list,
    }


def blueprint(modules):
    entries = []
    for module in modules:
        tag = module_identifier(module)
        entries.append(
            """cc_library_shared {
    name: "%(module)s",
    host_supported: true,
    srcs: ["forward_%(tag)s.S", "forward_%(tag)s.c"],
    cflags: ["-Wall", "-Werror"],
    // The proxy loads this module and then dlsyms the entry points out of it,
    // so nothing inside the build tree depends on these exports.
    ldflags: [],
}
"""
            % {"module": module, "tag": tag}
        )
    return (
        "// Generated by tools/gl-forwarders.py: host GL modules that the Digitalis\n"
        "// native-bridge proxies link against. Each stub jumps through a table the\n"
        "// constructor fills from the PenguDroid GL shim and host Mesa/glvnd.\n\n"
        + "\n".join(entries)
    )


def generate(destination, stub_source):
    """Write the forwarder tree into `destination`; return the written paths.

    `stub_source(library)` must return the NBS stub translation unit text for a
    stub library directory name.
    """
    import pathlib

    destination = pathlib.Path(destination)
    destination.mkdir(parents=True, exist_ok=True)
    written = []
    for module, (stub_library, sonames) in HOST_MODULES.items():
        functions, variables = stub_symbols(stub_source(stub_library), stub_library)
        if variables:
            raise ForwarderError(
                "%s declares interceptable variables (%s); the forwarder generator "
                "only emits functions" % (stub_library, ", ".join(variables))
            )
        tag = module_identifier(module)
        asm_path = destination / ("forward_%s.S" % tag)
        c_path = destination / ("forward_%s.c" % tag)
        asm_path.write_text(assembly(module, functions))
        c_path.write_text(initializer(module, functions, sonames))
        written += [asm_path, c_path]
    blueprint_path = destination / "Android.bp"
    blueprint_path.write_text(blueprint(HOST_MODULES))
    written.append(blueprint_path)
    return written
