import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Emits a typed, committed module from the audit snapshot in src/data/source/.
// The snapshot is a verbatim copy of docs/compatibility/index.json at the
// provenance version below, so this repository stays self-contained.
const here = dirname(fileURLToPath(import.meta.url));
const sourcePath = resolve(here, '../src/data/source/compatibility-index.json');
const outputPath = resolve(here, '../src/data/compatibility.generated.ts');

const index = JSON.parse(await readFile(sourcePath, 'utf8'));
const wired = index.jni.wired_slots.length;
const placeholders = index.jni.placeholder_slots.length;
const missingCalls = index.observations.unimplemented_methods;
const counts = index.scenario_counts;

if (index.scenarios.length !== 14) throw new Error(`Expected 14 scenarios, got ${index.scenarios.length}`);
if (missingCalls.length !== 71) throw new Error(`Expected 71 missing calls, got ${missingCalls.length}`);
if (wired !== 144 || placeholders !== 85) throw new Error(`Unexpected JNI counts: ${wired}/${placeholders}`);
if (counts.passed + counts.partial + counts.missing !== index.scenarios.length) {
  throw new Error('Scenario counts do not match the scenario list');
}

const scenarios = index.scenarios.map((scenario, i) => ({
  name: scenario.name,
  status: scenario.status,
  evidence: scenario.evidence,
  sortOrder: i + 1,
}));

const header = `// Generated by scripts/generate-data.mjs from src/data/source/compatibility-index.json,
// a verbatim snapshot of PenguDroid docs/compatibility/index.json at 0.3.0.
// Source: PenguDroid 0.3.0, backend "pengu". This is a scoped audit:
// JNI wiring plus a fixed 14-scenario foundation checklist, not a whole-Android
// completion percentage. See site/README.md ("Content honesty").
// Do not hand-edit; re-run the generator if the source audit changes.
import type { ScenarioSeed } from './types';

export const compatibilitySource = {
  schema: ${JSON.stringify(index.schema)},
  version: ${JSON.stringify(index.version)},
  backend: ${JSON.stringify(index.backend)},
  scope: ${JSON.stringify(index.scope)},
  wholeAndroidCompatibilityPercent: null,
  jni: {
    functionSlots: ${index.jni.function_slots},
    reservedSlotsExcluded: ${index.jni.reserved_slots_excluded},
    wired: ${wired},
    placeholders: ${placeholders},
  },
  counts: {
    passed: ${counts.passed},
    partial: ${counts.partial},
    missing: ${counts.missing},
  },
} as const;

export const auditedScenarios: ScenarioSeed[] = ${JSON.stringify(scenarios, null, 2)};

export const missingJavaCalls: string[] = ${JSON.stringify(missingCalls, null, 2)};
`;

await writeFile(outputPath, header, 'utf8');
console.log(`Wrote ${outputPath}: ${scenarios.length} scenarios, ${missingCalls.length} missing calls.`);
